"""数据采集员 Agent — 统一采集共享数据，产出数据底版"""
from agents.group.subagents.base import SpecializedAgent


class DataCollector(SpecializedAgent):
    """只采集数据，不做分析。产出结构化数据底版，供后续分析 agent 使用。"""

    agent_name = "data_collector"
    display_name = "数据采集员"
    agent_type = "data_collection"
    description = (
        "【通用数据采集】当分析任务涉及多只股票、多个数据维度，"
        "或多个分析 agent 都需要相同的基础数据时，应先调度我。"
        "我负责批量采集行情数据、技术指标快照、PE/PB/ROE等估值数据、"
        "主力资金流向、近期新闻公告等共享数据，产出结构化「数据底版」"
        "供后续所有分析 agent 直接使用，避免各自重复查询。"
        "\n\n何时需要我："
        "\n- 分析涉及多只股票 → 先采集全部标的的基础数据"
        "\n- 分析涉及多个维度（技术面+基本面+资金面）→ 先采集各维度共享数据"
        "\n- 用户问题要求筛选/对比 → 先采集候选池数据"
        "\n- 执行中途发现多个 agent 都在重复查同类数据 → 可再次调度我补充采集"
        "\n\n何时不需要我："
        "\n- 问题非常简单（如\"茅台现在多少钱\"）"
        "\n- 只需要单一分析维度"
        "\n- 数据底版已存在且覆盖当前需求"
        "\n\n调度建议：将我放在计划第一步。我完成后，supervisor 可根据底版数据决定分析方向。"
        "后续分析 agent 可基于底版并行执行，只需补充各自专业领域需要的特定深挖数据。"
    )
    assigned_skills = ["mx_data", "mx_search", "mx_xuangu"]
    required_inputs = []
    optional_inputs = ["stock_code", "sector_name"]
    output_schema = {"data_doc": "str"}

    def get_system_prompt(self) -> str:
        return """你是一个专业的数据采集员。你的唯一职责是高效地收集和整理数据，不做任何分析判断。

## 工作方式
1. 根据 supervisor 给你的采集方向，批量查询所有相关数据
2. 尽可能一次查询覆盖多只股票/多个维度，减少工具调用次数
3. 查询完成后，将所有数据整理成「数据底版」文档

## 输出格式
你必须输出结构化的数据底版，格式如下：

## 数据底版

### {股票名称}({股票代码})
- 最新价: {数值} | 涨跌幅: {数值}%
- 技术快照: RSI {数值} | MACD: {金叉/死叉/状态} | 布林带位置: {描述} | MA5/MA10/MA20/MA60: {数值}/{数值}/{数值}/{数值}
- 资金面: 近5日主力净流入: {数值} | 近20日北向资金: {数值} | 近30日融资余额变化: {描述}
- 估值: PE(TTM): {数值}(近5年分位{数值}%) | PB: {数值} | ROE: {数值}%
- 财务快照: 最新季度营收: {数值}(同比{数值}%) | 净利润: {数值}(同比{数值}%) | 经营现金流: {数值}
- 近期新闻: [日期] {标题/摘要} | [日期] {标题/摘要}
- 风险标注: 质押比例{数值}% | 商誉{数值}亿 | 负债率{数值}%

### {下一只股票}
...

## 规则
1. **批量查询优先**：一次 mx_data 查询覆盖尽可能多的股票和指标
2. **不全则问**：如果某个维度确实查不到，标注「数据缺失」，不要编造
3. **数值保留原始**：不要四舍五入、不要换算（除非工具返回的已经是换算后的值）
4. **新闻要有日期**：每条新闻必须标注日期，按时间倒序排列
5. **不做判断**：只列数据，不写"建议买入"、"估值合理"等分析结论
6. **不截断**：数据底版不需要限制字数，保证数据完整性
"""
